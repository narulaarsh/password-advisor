"""Builds the Elsevier (Journal of Information Security and Applications) version of the paper
from the IEEE source, so both versions share the same text, tables and numbers.

Usage: python docs/paper/make_jisa.py && (cd docs/paper/jisa && tectonic cav_jisa.tex)
Author declarations are left as bracketed items for the authors to complete.
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / 'jisa' / 'cav_jisa.tex'

HIGHLIGHTS = [
    'A fixed-weight contextual score cannot flag context-only risk below its threshold',
    'Frozen-protocol evaluation against matched baselines, rules and fitted models',
    'zxcvbn with user inputs doubled the fixed score\'s recall at the same operating rule',
    'A stronger attacker turned most context-rule false alarms into recovered passwords',
    'Authenticated backups, Argon2id calibration and concealed clipboard copies added',
]

PREAMBLE = r"""\documentclass[preprint,12pt]{elsarticle}
\usepackage{amsmath,amssymb}
\usepackage{fontspec}
\setmainfont{texgyretermes}[Extension=.otf, UprightFont=*-regular, BoldFont=*-bold,
  ItalicFont=*-italic, BoldItalicFont=*-bolditalic]
\setmonofont{texgyrecursor}[Extension=.otf, UprightFont=*-regular, BoldFont=*-bold,
  ItalicFont=*-italic, BoldItalicFont=*-bolditalic]
\usepackage{graphicx}
\usepackage{booktabs}
\usepackage{array}
\usepackage{url}
\usepackage{tikz}
\usetikzlibrary{positioning,arrows.meta,fit,backgrounds,calc}
\renewcommand{\arraystretch}{1.1}
\def\UrlBreaks{\do\/\do-\do.\do\#}
\setlength{\emergencystretch}{3em}
\journal{Journal of Information Security and Applications}

\begin{document}
\begin{frontmatter}
\title{TITLE}
\author[vit]{Jasmeet Ranjan Srivastava}
\author[vit]{Garvit Singla}
\author[vit]{Rakshit Kapoor}
\affiliation[vit]{organization={Department of Computer Science and Engineering (Information Security), Vellore Institute of Technology},
  city={Vellore}, state={Tamil Nadu}, country={India}}
% [Corresponding author: add \cortext and e-mail before submission.]
\begin{abstract}
ABSTRACT
\end{abstract}
\begin{highlights}
HIGHLIGHTS
\end{highlights}
\begin{keyword}
KEYWORDS
\end{keyword}
\end{frontmatter}
"""

DECLARATIONS = r"""
\section*{CRediT authorship contribution statement}
[To be completed by the authors, using the CRediT taxonomy, for Jasmeet Ranjan Srivastava, Garvit Singla and Rakshit Kapoor.]

\section*{Declaration of competing interest}
[The authors must state any competing interests, or declare that they have none.]

\section*{Funding}
[State the funding sources, or that the research received no specific grant.]

\section*{Data availability}
All data used in this study are synthetic and are regenerated by the scripts listed in the reproducibility paragraph. [State where the code and generated results are made available.]

\section*{Declaration of generative AI and AI-assisted technologies in the manuscript preparation process}
[Complete accurately before submission. AI coding and writing assistants were used during the revisions of this manuscript and its software. Name the tools and their purpose. State that the authors reviewed and edited all output and take full responsibility for the content of the publication.]

"""


def between(text, start, end):
    i = text.index(start) + len(start)
    return text[i:text.index(end, i)].strip()


def main():
    src = (HERE / 'cav_paper.tex').read_text(encoding='utf-8')
    title = between(src, r'\title{', '}\n')
    abstract = between(src, r'\begin{abstract}', r'\end{abstract}')
    keywords = between(src, r'\begin{IEEEkeywords}', r'\end{IEEEkeywords}').rstrip('.')
    for h in HIGHLIGHTS:
        assert len(h) <= 85, (len(h), h)
    end = src.index(r'\section*{Acknowledgment}') if r'\section*{Acknowledgment}' in src else src.index(r'\begin{thebibliography}')
    body = src[src.index(r'\section{Introduction}'):end]
    ai_statement = between(src, r'\section*{Acknowledgment}', r'\begin{thebibliography}') if end != src.index(r'\begin{thebibliography}') else None
    # The architecture figure is wider than the single-column text block.
    body = body.replace(r'\begin{tikzpicture}[', r'\resizebox{\textwidth}{!}{\begin{tikzpicture}[', 1)
    body = body.replace(r'\end{tikzpicture}', r'\end{tikzpicture}}', 1)
    # Column widths sized for IEEE two-column pages are rescaled to the single-column text block.
    for ieee, single in ((r'{@{}p{3.2cm}p{7.4cm}p{6.2cm}@{}}', r'{@{}p{0.21\textwidth}p{0.40\textwidth}p{0.31\textwidth}@{}}'),
                         (r'{@{}p{1.0cm}p{2.3cm}p{1.9cm}p{2.2cm}@{}}', r'{@{}p{0.15\textwidth}p{0.27\textwidth}p{0.22\textwidth}p{0.24\textwidth}@{}}')):
        assert body.count(ieee) == 1, ieee
        body = body.replace(ieee, single)
    bibliography = src[src.index(r'\begin{thebibliography}'):src.index(r'\end{thebibliography}') + len(r'\end{thebibliography}')]
    doc = (PREAMBLE.replace('TITLE', title).replace('ABSTRACT', abstract)
           .replace('HIGHLIGHTS', '\n'.join(r'\item ' + h.replace("'", "'") for h in HIGHLIGHTS))
           .replace('KEYWORDS', ' \\sep '.join(k.strip() for k in keywords.split(','))))
    declarations = DECLARATIONS
    if ai_statement:  # the IEEE acknowledgment becomes Elsevier's required AI declaration
        start = declarations.index('[Complete accurately before submission.')
        declarations = declarations[:start] + ai_statement + declarations[declarations.index(']', start) + 1:]
    doc += body + declarations + bibliography + '\n\\end{document}\n'
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(doc, encoding='utf-8')
    print(f'Wrote {OUT}')


if __name__ == '__main__':
    main()
